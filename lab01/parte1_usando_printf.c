/* Roteiro Aula 1 - Parte 1: Usando printf (Ficha do aluno) */

#include <stdio.h> /* biblioteca de entrada e saída (printf) */

int main(void) {
    /* cada printf imprime uma linha da ficha; \n pula para a próxima linha */
    printf("========================\n");
    printf(" FICHA DO ALUNO\n");
    printf("========================\n");
    printf("Nome: Leonardo Guimaraes\n"); /* dados personalizados */
    printf("Curso: Ciencia da Computacao\n");
    printf("Semestre: 2\n");
    printf("========================\n");

    return 0;
}
